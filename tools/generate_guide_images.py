def caption(key):return captions[key].replace('%%','%')

def fitted(text,width,size):
    while size>11 and font(size).getlength(text)>width:size-=1
    return font(size)
def page(title):
    im=Image.new('RGB',(960,320),'#111e2a');d=ImageDraw.Draw(im);d.rounded_rectangle((2,2,957,317),radius=14,outline='#416073',width=2)
    d.text((24,14),title,font=fitted(title,912,24),fill='#b4f1d4');return im,d
def card(d,x,y,w,h,title,sub,color='#24473e'):
    d.rounded_rectangle((x,y,x+w,y+h),radius=10,fill=color,outline='#a8bdb1',width=2)
