def pin(d,x,y,name,color='#e8b55f'):
    d.ellipse((x-6,y-6,x+6,y+6),fill=color,outline='#f5e4c5',width=2)
    d.text((x,y+10),name,anchor='mt',font=font(18),fill='#ffffff')
def wire(d,coords,color='#ed6b66',width=4):d.line(coords,fill=color,width=width,joint='curve')

